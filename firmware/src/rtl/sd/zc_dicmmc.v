module zc_divmmc(
    input wire clk,
    input wire reset,
    input wire divmmc_en,

    input wire ioreq,
    input wire iowr,
	 input wire iord,
	 input wire rom_m1_access,

    input wire [15:0] bus_a,
    input wire [7:0] bus_d,
    input wire bus_iorq_n,
    input wire bus_mreq_n,
    input wire bus_m1_n,
    input wire bus_wr_n,
    input wire bus_rd_n,
	 input wire bus_nmi_n,
    input wire btn_nmi_n,

    output wire sd_clk,
    input wire sd_do,
    output wire sd_di,
    output wire sd_cs_n,
	 
	 output wire [18:0] ram_a,
	 inout wire [7:0] ram_d,
	 output wire ram_rd_n,
	 output wire ram_wr_n,

    output reg [7:0] dout,
	 output wire divmmc_mem,
	 output wire [7:0] divmmc_dout,
    output wire busy
);

// SPI Z-Controller + DivMMC
wire zc_spi_start = (((bus_a[7:0] == 8'h57) | (divmmc_en & (bus_a[7:0] == 8'hEB))) & ioreq) ? 1 : 0;
wire zc_wr_en = (zc_spi_start & iowr) ? 1 : 0;
wire zc_rd_en = (zc_spi_start & iord) ? 1 : 0;
wire port77_wr = (((bus_a[7:0] == 8'h77) | (divmmc_en & (bus_a[7:0] == 8'hE7))) & iowr) ? 1 : 0;

reg zc_cs_n;
always @(posedge clk or posedge reset) begin
    if (reset) 
        zc_cs_n <= 1;
    else if (port77_wr) begin
        if (bus_a[7:0] == 8'hE7)
            zc_cs_n <= bus_d[0]; // divmmc uses bit0
        else
            zc_cs_n <= bus_d[1]; // zc uses bit1
    end
end

wire zc_sclk, zc_mosi;
wire [7:0] zc_do_bus;
zc_spi zc_spi(
    .clk_sys(clk),
    .ena(1),
    .tx(zc_wr_en),
    .rx(zc_rd_en),
    .din(bus_d),
    .dout(zc_do_bus),
    .spi_clk(zc_sclk),
    .spi_di(sd_do),
    .spi_do(zc_mosi),
    .spi_wait(busy)
);

assign sd_cs_n	= zc_cs_n;
assign sd_clk 	= (~zc_cs_n) ? zc_sclk : 1;
assign sd_di 	= (~zc_cs_n) ? zc_mosi : 1;

// ------------------------ divmmc-----------------------------
// Engineer:   Mario Prato
// 11.07.2013:OCH: adapted by me
// i take this implementation to correctly and easy make nmi 

reg mapterm, map3DXX, map1F00;
always @(*)
begin
    if (reset | ~divmmc_en) begin 
        mapterm <= 0;
        map3DXX <= 0;
        map1F00 <= 1;
    end
    else begin
         if ((bus_a == 16'h0000) | 
             (bus_a == 16'h0008) | 
             (bus_a == 16'h0038) | 
             (bus_a == 16'h0066) | 
             (bus_a == 16'h04c6) | 
             (bus_a == 16'h0562)) 
            mapterm <= 1;
        else 
            mapterm <= 0;

        // mappa 3D00 - 3DFF
        if (bus_a[15:8] == 8'b00111101) 
            map3DXX <= 1; 
        else 
            map3DXX <= 0;

        // 1ff8 - 1fff
        if (bus_a[15:3] == 13'b0001111111111) 
            map1F00 <= 0;
        else 
            map1F00 <= 1;
    end
end

reg mapcond, automap;
always @(posedge reset or negedge bus_mreq_n) begin
    if (reset | ~divmmc_en) begin
        mapcond <= 0;
        automap <= 0;
    end 
    else begin
        if (~bus_m1_n) begin
            mapcond <= (mapterm | map3DXX | (mapcond & map1F00)) & divmmc_en;
            automap <= (mapcond | map3DXX) & divmmc_en;
        end
    end
end

reg [7:0] port_e3_reg;
always @(posedge reset or posedge clk) begin
    if (reset) begin
        port_e3_reg[5:0] <= 6'b00000000;
		port_e3_reg[7] <= 0;
    end else if (iowr & (bus_a[7:0] == 8'hE3) & divmmc_en)	
		port_e3_reg <= {bus_d[7], port_e3_reg[6] | bus_d[6], bus_d[5:0]};
end

// nmi signal
assign bus_nmi_n = (~btn_nmi_n & divmmc_en & ~mapcond) ? 1'b0 : 
                   (~btn_nmi_n & ~divmmc_en & ~bus_m1_n & ~bus_mreq_n & (bus_a[15:14] != 2'b00)) ? 1'b0 : 1'bz;

// divmmc ram / rom

wire is_rom_divmmc = (divmmc_en & ~bus_mreq_n & (automap | port_e3_reg[7]) & (bus_a[15:13] == 3'b000)) ? 1 : 0;
wire is_ram_divmmc = (divmmc_en & ~bus_mreq_n & (automap | port_e3_reg[7]) & (bus_a[15:13] == 3'b001)) ? 1 : 0;
wire is_rom = (~bus_mreq_n & (bus_a[15:14] == 2'b00)) ? 1 : 0;
wire is_ram = (~bus_mreq_n & ~is_rom) ? 1 : 0;

wire [7:0] rom_do;
wire [12:0] rom_a = (is_rom_divmmc) ? bus_a[12:0] : rom_a;
// mem generated by: 
// hexdump -v -e '1/1 "%02x\n"' esxdos089.bin > esxdos.mem
dprom #(.ADDRWIDTH(13), .MEM_INIT_FILE("esxdos.mem")) esxdos_rom(
	.clock(clk),
	.address_a(rom_a),
	.q_a(rom_do)
);

