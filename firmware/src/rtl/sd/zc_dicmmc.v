	.address_a({port_e3_reg[2:0], bus_a[12:0]}),
	.data_a(bus_d),
	.wren_a(is_ram_divmmc & ~bus_wr_n),
	.q_a(),
	.address_b({port_e3_reg[2:0], bus_a[12:0]}),
	.data_b(8'hFF),
	.wren_b(1'b0),
	.q_b(ram_do)
);*/

assign ram_a = (is_ram_divmmc) ? {port_e3_reg[5:0], bus_a[12:0]} : ram_a;
assign ram_d = (is_ram_divmmc & ~bus_wr_n) ? bus_d : 8'bz;
assign ram_wr_n = (is_ram_divmmc & ~bus_wr_n) ? 1'b0 : 1'b1;
assign ram_rd_n = (is_ram_divmmc & ~bus_rd_n) ? 1'b0 : 1'b1;

assign divmmc_mem = (is_rom_divmmc | is_ram_divmmc) ? 1 : 0;
assign divmmc_dout = (is_rom_divmmc) ? rom_do : 
						   (is_ram_divmmc) ? ram_d : divmmc_dout;

always @(*) begin
		casex ({divmmc_en, bus_a[7:0]})
			{1'bx, 8'h77}: dout <= {~busy, 7'b1111100};
			{1'bx, 8'h57}: dout <= zc_do_bus;
			{1'b1, 8'hEB}: dout <= zc_do_bus;
		endcase
end

endmodule

